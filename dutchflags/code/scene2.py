from manim import *


class scene2(Scene):
    def construct(self):
        DARK_RED = ManimColor("#C8102E")
        s1 = Rectangle(width=9, height=2, color=DARK_RED, fill_opacity=1)
        s2 = Rectangle(width=9, height=2, color=WHITE, fill_opacity=1)
        s3 = Rectangle(width=9, height=2, color=YELLOW, fill_opacity=1)
        flag = VGroup(s1, s2, s3).arrange(DOWN, buff=0)
        self.play(Write(flag), run_time=3)
        title1 = Text("Spaans Nederland", font_size=32, color=WHITE).next_to(flag, DOWN).shift(LEFT * 1)
        subtitle1 = Text("1482 - 1581", font_size=28, color=WHITE).next_to(title1, RIGHT)
        self.play(Write(title1), run_time=1)
        self.play(Write(subtitle1), run_time=1)
        self.wait(2)
        self.play(Unwrite(title1), run_time=1)
        self.play(Unwrite(subtitle1), run_time=1)
        self.wait(0.5)
        self.play(flag[0].animate.set_color(ORANGE), flag[2].animate.set_color(DARK_BLUE), run_time=1)
        title2 = Text("Prinsjesvlag", font_size=32, color=WHITE).next_to(flag, DOWN).shift(LEFT * 1)
        subtitle2 = Text("1579 - 1652", font_size=28, color=WHITE).next_to(title2, RIGHT)
        self.play(Write(title2), run_time=1)
        self.play(Write(subtitle2), run_time=1)
        self.wait(2)
        self.play(Unwrite(title2), run_time=1)
        self.play(Unwrite(subtitle2), run_time=1)
        self.wait(0.5)
        self.play(flag[0].animate.set_color(DARK_RED), run_time=1)
        title3 = Text("Koninkrijk der Nederlanden", font_size=32, color=WHITE).next_to(flag, DOWN).shift(LEFT * 1)
        subtitle3 = Text("1652 - Heden", font_size=28, color=WHITE).next_to(title3, RIGHT)
        self.play(Write(title3), run_time=1)
        self.play(Write(subtitle3), run_time=1)
        self.wait(2)
        self.play(Unwrite(title3), run_time=1)
        self.play(Unwrite(subtitle3), run_time=1)
        self.play(Uncreate(flag), run_time=1)
        self.wait(2)
        
